"""Flat, collective structural validation of already evaluated finite values.

This traverses immutable host storage only. Scientific expressions and kernels
remain statically generated by the existing Program emitters.
"""

from __future__ import annotations

from typing import Any
from contextvars import ContextVar
from functools import wraps

from pops._structural_data import canonical_json


def _leaf(signature, token, lines):
    from .program_emit_finite_arrays import _check_domain
    from .program_emit_structured_control import _reject_if, _uniform_int

    kind = signature["vtype"]
    if signature.get("ownership") == "contiguous_distributed":
        from .program_emit_distributed_arrays import uniform_reference

        uniform_reference(signature, token, lines)
    elif kind == "index_set":
        _check_domain(signature, token, lines)
    elif kind in ("state", "rhs", "scalar_field"):
        # The replicated outer Array does not replicate a MultiFab's local cells.
        pass
    elif kind == "scalar":
        _reject_if(
            "!std::isfinite(%s)" % token,
            lines,
            "replicated array has a nonfinite element",
        )
        _uniform_int(
            "std::bit_cast<std::int64_t>(pops::Real(%s))" % token,
            lines,
            "replicated array Float64 bits differ across execution ranks",
        )
    elif kind in ("int64", "bool"):
        _uniform_int(
            "std::int64_t(%s)" % token,
            lines,
            "replicated array element differs across execution ranks",
        )
    elif kind == "index":
        _reject_if(
            "!(%s).domain || !(%s).domain->visible() || (%s).offset < 0 || "
            "(%s).offset >= (%s).domain->size" % ((token,) * 5),
            lines,
            "replicated array contains an invalid Index",
        )
        for expression in (
            "(%s).offset" % token,
            "(%s).domain->family" % token,
            "(%s).domain->version" % token,
            "(%s).domain->size" % token,
        ):
            _uniform_int(
                expression,
                lines,
                "replicated Index instance differs across execution ranks",
            )
    else:
        raise TypeError("unsupported replicated array element type %r" % kind)


def _layout(signature):
    """Build occurrence schemas, flat Record offsets and stack depth iteratively."""
    nodes: list[dict[str, Any]] = []
    active: set[int] = set()
    stack: list[tuple[Any, int | None, int, bool]] = [(signature, None, 1, False)]
    while stack:
        sig, parent, depth, leaving = stack.pop()
        identity = id(sig)
        if leaving:
            active.remove(identity)
            continue
        if identity in active:
            raise ValueError("cyclic structural uniformity signature")
        active.add(identity)
        index = len(nodes)
        node = {"signature": sig, "children": [], "depth": depth}
        nodes.append(node)
        if parent is not None:
            nodes[parent]["children"].append(index)
        kind = sig["vtype"]
        children = (
            ()
            if sig.get("ownership") == "contiguous_distributed"
            else (sig["element"],)
            if kind == "array"
            else tuple(child for _, child in sig["members"])
            if kind in ("product", "variant")
            else ()
        )
        stack.append((sig, parent, depth, True))
        stack.extend((child, index, depth + 1, False) for child in reversed(children))
    for node in reversed(nodes):
        kind = node["signature"]["vtype"]
        node["offsets"] = []
        width = 1 if kind == "variant" else 0
        if kind in ("product", "variant"):
            for child in node["children"]:
                node["offsets"].append(width)
                width += nodes[child]["width"]
        else:
            width = 1
        node["width"] = width
    return nodes, max(node["depth"] for node in nodes)


def _cell(lines):
    from .program_emit_structured_control import _reject_if

    _reject_if(
        "!frame.cell && (!frame.record || frame.offset >= frame.record->values.size())",
        lines,
        "replicated structural value has no storage cell",
    )
    lines.append(
        "const std::any* cell = frame.cell ? frame.cell : &frame.record->values[frame.offset];"
    )


def _record(node, lines):
    from .program_emit_structured_control import _reject_if

    lines.append("if (!frame.record) {")
    _cell(lines)
    lines.append("frame.record = std::any_cast<pops_algebra_finite::Record>(cell);")
    _reject_if(
        "!frame.record || frame.record->values.size() != %d" % node["width"],
        lines,
        "replicated Record has an invalid storage layout",
    )
    lines += ["frame.offset = 0;", "}"]
    _reject_if(
        "frame.offset > frame.record->values.size() || %d > frame.record->values.size()-frame.offset"
        % node["width"],
        lines,
        "replicated Record slice is outside its storage",
    )


def _push_record_child(child, offset, lines):
    lines += [
        "const auto* record = frame.record;",
        "const auto offset = frame.offset + %d;" % offset,
        "stack[top++] = UniformFrame{%d, nullptr, record, nullptr, offset};" % child,
    ]


def _traverse(nodes, token, root, depth, lines):
    from .program_emit_finite_arrays import _allocate, _check_domain, finite_cpp_type
    from .program_emit_structured_control import _reject_if, _uniform_int

    lines += [
        "{",
        "const auto& uniform_root = %s;" % token,
        "struct UniformFrame {",
        "  std::size_t schema = 0; const std::any* cell = nullptr;",
        "  const pops_algebra_finite::Record* record = nullptr;",
        "  const pops_algebra_finite::Array* array = nullptr;",
        "  std::size_t offset = 0, cursor = 0; bool entered = false;",
        "};",
        "std::vector<UniformFrame> stack;",
    ]
    _allocate("std::vector<UniformFrame>(%s)" % depth, "stack", lines)
    lines += [
        "std::size_t top = 1;",
        "stack[0].array = &uniform_root;",
        "stack[0].schema = %s;" % root,
        "while (top != 0) {",
        "auto& frame = stack[top-1];",
        "switch (frame.schema) {",
    ]
    for number, node in enumerate(nodes):
        sig = node["signature"]
        kind = sig["vtype"]
        distributed = sig.get("ownership") == "contiguous_distributed"
        lines.append("case %d: {" % number)
        if kind in ("product", "variant"):
            lines.append("if (!frame.entered) {")
            _record(node, lines)
            lines.append("frame.entered = true;")
            if kind == "variant":
                lines.append(
                    "const auto* tag = std::any_cast<std::int64_t>(&frame.record->values[frame.offset]);"
                )
                _reject_if(
                    "!tag", lines, "replicated Variant has an invalid tag storage type"
                )
                _uniform_int(
                    "*tag",
                    lines,
                    "replicated Variant tag differs across execution ranks",
                )
                _reject_if(
                    "*tag < 0 || *tag >= %d" % len(node["children"]),
                    lines,
                    "replicated Variant has an invalid discriminant",
                )
                lines.append("switch (*tag) {")
                for arm, (child, offset) in enumerate(
                    zip(node["children"], node["offsets"], strict=True)
                ):
                    lines.append("case %d: {" % arm)
                    _push_record_child(child, offset, lines)
                    lines += ["break;", "}"]
                lines += ["}", "} else { --top; }"]
            else:
                lines += ["}", "switch (frame.cursor++) {"]
                for arm, (child, offset) in enumerate(
                    zip(node["children"], node["offsets"], strict=True)
                ):
                    lines.append("case %d: {" % arm)
                    _push_record_child(child, offset, lines)
                    lines += ["break;", "}"]
                lines += ["default: --top; break;", "}"]
        elif kind == "array" and not distributed:
            lines += ["if (!frame.entered) {", "if (!frame.array) {"]
            _cell(lines)
            lines.append(
                "frame.array = std::any_cast<pops_algebra_finite::Array>(cell);"
            )
            _reject_if(
                "!frame.array", lines, "replicated Array has an invalid storage type"
            )
            lines.append("}")
            _check_domain(sig, "frame.array->domain", lines)
            _reject_if(
                "!frame.array->values || frame.array->values->size() != std::size_t(frame.array->domain->size)",
                lines,
                "replicated nested Array has an invalid buffer",
            )
            lines += [
                "frame.entered = true;",
                "}",
                "if (frame.cursor < frame.array->values->size()) {",
                "const std::any* child = &(*frame.array->values)[frame.cursor++];",
                "stack[top++] = UniformFrame{%d, child};" % node["children"][0],
                "} else { --top; }",
            ]
        elif kind in ("state", "rhs", "scalar_field"):
            lines.append("--top;")
        else:
            _cell(lines)
            lines.append(
                "const auto* value = std::any_cast<%s>(cell);" % finite_cpp_type(sig)
            )
            _reject_if(
                "!value",
                lines,
                "replicated structural leaf has an invalid storage type",
            )
            _leaf(sig, "(*value)", lines)
            lines.append("--top;")
        lines += ["break;", "}"]
    lines.append("default: {")
    _reject_if("true", lines, "replicated structural traversal has an invalid schema")
    lines += ["break;", "}", "}", "}", "}"]


class _SchemaRegistry:
    """One exact storage DAG per translation unit; no evaluated value is cached."""

    def __init__(self):
        self.nodes: list[dict[str, Any]] = []
        self.identities: dict[str, int] = {}
        self.sealed = False

    def intern(self, signature):
        from pops.time.canonical_data import _json_ready

        if self.sealed:
            raise RuntimeError(
                "structural validation registered after its definitions were emitted"
            )
        occurrences, depth = _layout(signature)
        resolved: dict[int, int] = {}
        for index in range(len(occurrences) - 1, -1, -1):
            node = occurrences[index]
            children = tuple(resolved[child] for child in node["children"])
            data = dict(node["signature"])
            kind = data["vtype"]
            if data.get("ownership") != "contiguous_distributed":
                if kind == "array":
                    data["element"] = children[0]
                elif kind in ("product", "variant"):
                    data["members"] = tuple(
                        (name, child)
                        for (name, _), child in zip(
                            data["members"], children, strict=True
                        )
                    )
            # Every other signature field remains in the key: ownership,
            # domains, capacities, scientific authorities and parameter points.
            # Child IDs avoid reserializing the whole recursively shared type.
            identity = canonical_json(_json_ready(data), allow_nan=False)
            identifier = self.identities.get(identity)
            if identifier is None:
                identifier = len(self.nodes)
                self.identities[identity] = identifier
                self.nodes.append(dict(node, children=children))
            resolved[index] = identifier
        return resolved[0], depth


_ACTIVE: ContextVar[_SchemaRegistry | None] = ContextVar(
    "pops_uniform_validation", default=None
)
_VALIDATOR = "pops_validate_uniform_structural_array"


def uniform_scope(function):
    @wraps(function)
    def emit(*args, **kwargs):
        token = _ACTIVE.set(_SchemaRegistry())
        try:
            return function(*args, **kwargs)
        finally:
            _ACTIVE.reset(token)

    return emit


def uniform_definitions():
    registry = _ACTIVE.get()
    if registry is None:
        raise RuntimeError(
            "structural validation definitions require an emission scope"
        )
    if registry.sealed:
        raise RuntimeError("structural validation definitions were already emitted")
    registry.sealed = True
    if not registry.nodes:
        return ""
    lines = [
        "// pops-shared-structural-validation@1 schemas=%d" % len(registry.nodes),
        "template<class Context>",
        "[[maybe_unused]] static void %s(Context& ctx, const pops_algebra_finite::Array& input,"
        % _VALIDATOR,
        "    const std::size_t root_schema, const std::size_t maximum_depth) {",
    ]
    _traverse(registry.nodes, "input", "root_schema", "maximum_depth", lines)
    lines.append("}")
    return "\n".join(lines) + "\n"


def _array(signature, token, lines):
    registry = _ACTIVE.get()
    if registry is None:
        # Standalone lowering utilities use the same DAG and traversal in their
        # caller's scope; full Program translation units share one definition.
        registry = _SchemaRegistry()
        root, depth = registry.intern(signature)
        _traverse(registry.nodes, token, root, depth, lines)
    else:
        root, depth = registry.intern(signature)
        lines.append("%s(ctx, %s, %d, %d);" % (_VALIDATOR, token, root, depth))


def uniform_element(signature, token, lines):
    """Emit bounded C++ scopes even for arbitrarily deep valid structural types."""
    from .program_emit_structured_control import _reject_if, _uniform_int

    _layout(signature)  # Reject cyclic signatures before emitting any partial C++.
    lines.append("{")
    stack = [(signature, token, "true")]
    flags = 0
    while stack:
        sig, value, active = stack.pop()
        kind = sig["vtype"]
        if kind == "product":
            stack.extend(
                (child, value[key], active) for key, child in reversed(sig["members"])
            )
        elif kind == "variant":
            lines.append("if (%s) {" % active)
            _uniform_int(
                value["tag"],
                lines,
                "replicated Variant tag differs across execution ranks",
            )
            _reject_if(
                "%s < 0 || %s >= %d"
                % (value["tag"], value["tag"], len(sig["members"])),
                lines,
                "replicated Variant has an invalid discriminant",
            )
            lines.append("}")
            children = []
            for arm, (key, child) in enumerate(sig["members"]):
                flag = "uniform_active_%d" % flags
                flags += 1
                lines.append(
                    "const bool %s = %s && (%s) == %d;"
                    % (flag, active, value["tag"], arm)
                )
                children.append((child, value["payloads"][key], flag))
            stack.extend(reversed(children))
        else:
            lines.append("if (%s) {" % active)
            if kind == "array" and sig.get("ownership") != "contiguous_distributed":
                _array(sig, value, lines)
            else:
                _leaf(sig, value, lines)
            lines.append("}")
    lines.append("}")
