"""pops.codegen.amr_program_context_unit -- one AMR Program context per compile identity.

Every AMR Program instantiates ``AmrProgramContext<Dim>`` from the same frozen engine headers, and
that generic code is most of the compile time of each Program. A generated AMR Program declares the
instantiation ``extern`` after the context header; ``compile_problem`` links it with this fixed
unit, compiled once per artifact-spec identity with the Program's compiler, flags and header
signature. The context therefore keeps the Program's floating-point policy (CC7), and each Program
library still carries the whole context, without a dependency on another library.
"""

from __future__ import annotations

import hashlib
from typing import Any

AMR_PROGRAM_CONTEXT_INCLUDE = "#include <pops/runtime/program/amr_program_context.hpp>"
AMR_PROGRAM_CONTEXT_EXTERN = (
    "extern template class pops::runtime::program::AmrProgramContext<pops::kNativeDimension>;"
)
_AMR_PROGRAM_CONTEXT_INSTANTIATION = (
    "template class pops::runtime::program::AmrProgramContext<pops::kNativeDimension>;"
)
# Program-specific includes of the Program template; the unit keeps only its fixed preamble.
_PROGRAM_VARIABLE_INCLUDES = "{prepared_native_component_includes}{block_inverse_include}"


def amr_program_context_include(comment: str = "") -> str:
    """Include the AMR Program context and leave its instantiation to the shared unit."""
    return "%s%s\n%s\n" % (AMR_PROGRAM_CONTEXT_INCLUDE, comment, AMR_PROGRAM_CONTEXT_EXTERN)


def amr_program_context_unit_source() -> str:
    """Return the unit: the fixed Program preamble, the context header and its instantiation.

    The unit includes the headers of every Program in the same order, so the instantiated members
    see the declarations that a Program translation unit sees.
    """
    from .program_emit_kernels import _PROGRAM_CPP_TEMPLATE

    preamble = _PROGRAM_CPP_TEMPLATE.split("{model_helpers}", 1)[0]
    if preamble.count(_PROGRAM_VARIABLE_INCLUDES) != 1:
        raise RuntimeError("the Program template preamble changed its Program-specific includes")
    preamble = preamble.replace(_PROGRAM_VARIABLE_INCLUDES, "")
    lines = preamble.splitlines()
    while lines and lines[0].startswith("//"):
        lines.pop(0)
    if any("{" in line or "}" in line for line in lines):
        raise RuntimeError("the Program template preamble has an unresolved placeholder")
    return "".join((
        "// GENERATED by pops.codegen.amr_program_context_unit. Do not edit.\n",
        "// The AMR Program context, instantiated once for every Program of one compile identity.\n",
        "\n".join(lines).rstrip("\n"),
        "\n\n",
        AMR_PROGRAM_CONTEXT_INCLUDE,
        "\n",
        _AMR_PROGRAM_CONTEXT_INSTANTIATION,
        "\n",
    ))


def amr_program_context_unit_identity(
    *, compiler: str, standard: str, abi_key: str, optflags: Any, cflags: Any,
    toolchain_capture: Any, native_dimension: int,
) -> tuple[Any, Any]:
    """Return the semantic and artifact-spec identities of the unit for one Program compile.

    The unit is a function of the frozen engine headers (in ``abi_key``), the toolchain, the compile
    flags and the native dimension; its source is fixed.
    """
    from pops.codegen.cache import _precision_cache_key, _registry_cache_key
    from pops.codegen.toolchain import _native_feature_key, native_compiler_command_contract
    from pops.identity import artifact_spec_identity
    from pops.identity.semantic import semantic_identity

    source = amr_program_context_unit_source()
    semantic = semantic_identity({
        "kind": "amr-program-context-unit",
        "native_dimension": native_dimension,
    })
    spec = artifact_spec_identity(
        semantic,
        target="amr_system",
        backend="production",
        precision=_precision_cache_key(),
        abi=abi_key,
        toolchain="%s|%s" % (compiler, standard),
        routes={"registry": _registry_cache_key(), "features": _native_feature_key()},
        components={
            **native_compiler_command_contract(compiler),
            "generated_source": hashlib.sha256(source.encode("utf-8")).digest(),
            "native_dependency_contract": (
                "compiler-observed-sdk-metadata-v2" if toolchain_capture is not None
                else "compiler-observed-v1"),
            **({"native_toolchain_metadata": toolchain_capture.to_data()}
               if toolchain_capture is not None else {}),
            "native_dimension": native_dimension,
        },
        flags=[*optflags, *cflags],
    )
    return semantic, spec


